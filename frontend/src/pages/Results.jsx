import { useLocation, useNavigate, Link } from 'react-router-dom';
import { motion } from 'framer-motion';
import { ArrowRight, BookOpen, Brain, Home, RotateCcw, Smartphone, Zap } from 'lucide-react';
import { PieChart, Pie, Cell, ResponsiveContainer } from 'recharts';
import Nova from '../components/Nova';
import { getWellnessRecommendations } from '../utils/recommendations';

const Results = () => {
  const location = useLocation();
  const navigate = useNavigate();
  const { score, formData } = location.state || {};

  if (!score && score !== 0) {
    return (
      <div className="max-w-2xl mx-auto px-4 py-20">
        <div className="card text-center">
          <h1 className="section-head" style={{ fontSize: '2rem', marginBottom: '0.8rem' }}>No results found</h1>
          <p className="subtle-copy" style={{ marginBottom: '1.4rem' }}>Please complete the assessment to see your predicted score.</p>
          <Link to="/assessment" className="btn-primary">Go to assessment</Link>
        </div>
      </div>
    );
  }

  const scoreData = [
    { name: 'Your score', value: Number(score) },
    { name: 'Remaining', value: Math.max(0, 10 - Number(score)) },
  ];

  const palette = ['#5c8dff', '#dfe9ff'];

  const recommendations = getWellnessRecommendations(formData || {});

  const summaryCards = [
    { label: 'Daily usage', value: `${Number(formData.avg_daily_usage_hours || 0).toFixed(1)} hrs`, icon: Smartphone },
    { label: 'Study hours', value: `${Number(formData.study_hours || 0).toFixed(1)} hrs`, icon: BookOpen },
    { label: 'Sleep', value: `${Number(formData.sleep_hours_per_night || 0).toFixed(1)} hrs`, icon: Zap },
    { label: 'Stress', value: formData.stress_level || 'Not set', icon: Brain },
  ];

  const summaryRows = [
    { label: 'Age', value: `${formData.age} years` },
    { label: 'Gender', value: formData.gender },
    { label: 'Country', value: formData.country },
    { label: 'Academic Level', value: formData.academic_level },
    { label: 'Most Used Platform', value: formData.most_used_platform },
    { label: 'Purpose of Use', value: formData.purpose_of_use },
    { label: 'Daily Usage', value: `${Number(formData.avg_daily_usage_hours || 0).toFixed(1)} hrs/day` },
    { label: 'Daily Unlocks', value: formData.daily_unlocks },
    { label: 'Study Hours', value: `${Number(formData.study_hours || 0).toFixed(1)} hrs` },
    { label: 'Physical Activity', value: `${Number(formData.physical_activity_hours || 0).toFixed(1)} hrs` },
    { label: 'Sleep', value: `${Number(formData.sleep_hours_per_night || 0).toFixed(1)} hrs/night` },
    { label: 'Stress', value: formData.stress_level },
  ];

  const profileBars = [
    { label: 'Sleep', value: Number(formData.sleep_hours_per_night || 0), max: 10 },
    { label: 'Study', value: Number(formData.study_hours || 0), max: 12 },
    { label: 'Physical activity', value: Number(formData.physical_activity_hours || 0), max: 6 },
    { label: 'Digital usage', value: Number(formData.avg_daily_usage_hours || 0), max: 8 },
    { label: 'Daily unlocks', value: Number(formData.daily_unlocks || 0), max: 80 },
    { label: 'Stress', value: { Low: 2, Medium: 4, High: 6, 'Very High': 8 }[formData.stress_level] || 4, max: 8 },
  ];

  return (
    <div className="result-shell max-w-7xl mx-auto px-4 sm:px-6 lg:px-8 py-12">
      <div className="result-header">
        <h1>Your Assessment Results</h1>
        <Nova state="results" compact avatar="bunty3" message="Your results are ready! 💙" />
      </div>

      <div className="result-score-grid">
        <div className="card score-card">
          <div className="score-label">ML Predicted Score</div>
          <div className="score-large">{Number(score).toFixed(2)}</div>
          <p className="score-summary">Your score is generated by a machine-learning model from the information you provided.</p>
        </div>

        <div className="card score-gauge-wrap">
          <ResponsiveContainer width="100%" height={260}>
            <PieChart>
              <Pie data={scoreData} dataKey="value" innerRadius={72} outerRadius={92} startAngle={90} endAngle={-270} paddingAngle={2}>
                {scoreData.map((entry, index) => (
                  <Cell key={index} fill={palette[index]} />
                ))}
              </Pie>
            </PieChart>
          </ResponsiveContainer>
          <div className="score-gauge-text">{Number(score).toFixed(2)}/10</div>
        </div>
      </div>

      <div className="summary-grid" style={{ marginTop: '1.6rem' }}>
        {summaryCards.map(({ label, value, icon: Icon }) => (
          <div key={label} className="summary-item">
            <span className="summary-item-label">{label}</span>
            <div style={{ display: 'flex', alignItems: 'center', justifyContent: 'space-between', marginTop: '0.6rem' }}>
              <span className="summary-item-value">{value}</span>
              <span className="feature-icon" style={{ width: '2.3rem', height: '2.3rem' }}><Icon size={16} /></span>
            </div>
          </div>
        ))}
      </div>

      <div style={{ marginTop: '2rem' }} className="snapshot-grid">
        <div className="card">
          <h3 style={{ marginTop: 0, marginBottom: '1rem', fontSize: '1.5rem' }}>Assessment Snapshot</h3>
          <div className="list-card">
            {summaryRows.map(({ label, value }) => (
              <div key={label} className="list-row">
                <span className="subtle-copy">{label}</span>
                <strong>{value}</strong>
              </div>
            ))}
          </div>
        </div>

        <div className="card">
          <h3 style={{ marginTop: 0, marginBottom: '1rem', fontSize: '1.5rem' }}>Your Wellness Profile</h3>
          <div className="profile-grid">
            {profileBars.map(({ label, value, max }) => (
              <div key={label} className="list-card" style={{ marginBottom: '0.85rem' }}>
                <div style={{ display: 'flex', justifyContent: 'space-between', marginBottom: '0.5rem' }}>
                  <span>{label}</span>
                  <strong>{value}</strong>
                </div>
                <div style={{ height: '10px', borderRadius: '999px', background: 'rgba(148,163,184,0.18)' }}>
                  <div style={{ width: `${Math.min((value / max) * 100, 100)}%`, height: '100%', background: 'linear-gradient(90deg,#5c8dff,#8ddcfb)', borderRadius: '999px' }} />
                </div>
              </div>
            ))}
          </div>
        </div>
      </div>

      <div style={{ marginTop: '2rem' }}>
        <div className="card">
          <div style={{ display: 'flex', alignItems: 'center', justifyContent: 'space-between', gap: '1rem', marginBottom: '1rem', flexWrap: 'wrap' }}>
            <h3 style={{ margin: 0, fontSize: '1.7rem' }}>Personalized Wellness Suggestions</h3>
            <Nova state="encouraging" compact avatar="bunty3" message="Your results are ready! 💙\nHere are a few areas you may want to pay attention to." />
          </div>

          <div className="profile-grid">
            {recommendations.map(({ icon, title, text }) => (
              <div key={title} className="recommendation-card">
                <div className="recommendation-header">
                  <span>{icon}</span>
                  <span className="recommendation-title">{title}</span>
                </div>
                <p className="subtle-copy" style={{ margin: 0, lineHeight: 1.7 }}>{text}</p>
              </div>
            ))}
          </div>
        </div>
      </div>

      <div style={{ marginTop: '2rem' }} className="card accordion">
        <details open>
          <summary>What does this score mean?</summary>
          <div className="accordion-content">
            This is a machine-learning prediction generated from the information provided during the assessment. It is intended for educational and project demonstration purposes and should not be interpreted as a medical diagnosis.
          </div>
        </details>
      </div>

      <div className="privacy-box" style={{ marginTop: '1.4rem' }}>
        <div className="feature-icon" style={{ width: '2.5rem', height: '2.5rem' }}><Brain size={16} /></div>
        <div>
          <strong style={{ display: 'block', marginBottom: '0.25rem' }}>Your information matters.</strong>
          <span className="subtle-copy">This project uses the assessment data you submit to generate a prediction in the browser and send it to the local FastAPI backend for processing. It does not claim permanent storage or secure medical handling beyond the local demo setup.</span>
        </div>
      </div>

      <motion.div initial={{ opacity: 0, y: 14 }} animate={{ opacity: 1, y: 0 }} transition={{ duration: 0.5 }} style={{ marginTop: '2rem', display: 'flex', flexWrap: 'wrap', gap: '1rem' }}>
        <button onClick={() => navigate('/assessment', { state: { fromResults: true, previousData: formData } })} className="btn-primary">
          <RotateCcw size={16} /> Edit Responses
        </button>
        <Link to="/" className="btn-secondary"><Home size={16} /> Home</Link>
      </motion.div>
    </div>
  );
};

export default Results;
